"""Generate supabase/seed.sql from Data/sites.json.

Usage: python3 -I scripts/make_seed.py
sites.json is the source of truth; rerun this after editing it.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "Data" / "sites.json"
OUT = ROOT / "supabase" / "seed.sql"


def lit(value):
    if value is None:
        return "null"
    return "'" + str(value).replace("'", "''") + "'"


def jsonb(value):
    return "null" if value is None else lit(json.dumps(value, ensure_ascii=False)) + "::jsonb"


def text_array(values):
    return "array[" + ", ".join(lit(v) for v in values) + "]::text[]"


data = json.loads(SRC.read_text(encoding="utf-8"))
rows = []
for s in data["sites"]:
    rows.append("  (" + ", ".join([
        lit(s["id"]), lit(data["body"]), lit(s["mission"]), str(s["order"]), lit(s["label"]),
        lit(s["lander"]), jsonb(s["region"]), lit(s["landedAt"]),
        text_array(s["crew"]["surface"]), lit(s["crew"].get("orbit")),
        repr(s["coordinates"]["lat"]), repr(s["coordinates"]["lon"]),
        jsonb(s["leftBehind"]), jsonb(s["story"]), jsonb(s["photo"]),
    ]) + ")")

values_sql = ",\n".join(rows)
sql = f"""-- Generated by scripts/make_seed.py from Data/sites.json. Do not edit by hand.
insert into public.sites
  (id, body, mission, mission_order, label, lander, region, landed_at,
   crew_surface, crew_orbit, lat, lon, left_behind, story, photo)
values
{values_sql}
on conflict (id) do update set
  body = excluded.body, mission = excluded.mission, mission_order = excluded.mission_order,
  label = excluded.label, lander = excluded.lander, region = excluded.region,
  landed_at = excluded.landed_at, crew_surface = excluded.crew_surface,
  crew_orbit = excluded.crew_orbit, lat = excluded.lat, lon = excluded.lon,
  left_behind = excluded.left_behind, story = excluded.story, photo = excluded.photo,
  updated_at = now();
"""
OUT.write_text(sql, encoding="utf-8")
print(f"Wrote {len(rows)} sites to {OUT.relative_to(ROOT)}")
